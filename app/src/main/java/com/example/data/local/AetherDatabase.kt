        /**
         * Non-destructive Migration from Database v10 to v11:
         * One-time data repair for the "phantom grace days" bug. Before this fix, the weekly
         * Grace Day counter only reset when the app happened to be opened ON a Monday
         * (checking `today.dayOfWeek == MONDAY`) instead of checking whether a Monday had
         * occurred at all since the last time the app was used. Any user who skipped opening
         * the app across a Monday kept a stale, non-zero `graceDaysUsed` carried over from a
         * previous week — even though they never actually used a Grace Day in the new week.
         * The rollover logic itself is already fixed (see AetherDateUtils.hasMondayBetween),
         * but that fix only affects the calculation going forward: it cannot retroactively
         * correct values already sitting in the database from before the fix existed. This
         * migration clears that stale count once so every habit starts the new logic clean.
         */
        val MIGRATION_10_11 = object : Migration(10, 11) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL("UPDATE `habits` SET `graceDaysUsed` = 0")
            }
        }

        /**
         * Non-destructive Migration from Database v11 to v12:
         * Adds the indices that day-scoped queries actually rely on. Every meal query now
         * filters by dateIso, and completion logs are frequently looked up by itemId (per-item
         * history, duplicate-log checks during rollover). Without these, both were full table
         * scans that get progressively slower as history accumulates.
         */
        val MIGRATION_11_12 = object : Migration(11, 12) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL("CREATE INDEX IF NOT EXISTS `index_meals_dateIso` ON `meals` (`dateIso`)")
                db.execSQL("CREATE INDEX IF NOT EXISTS `index_completion_logs_itemId` ON `completion_logs` (`itemId`)")
            }
        }

        /**
         * Non-destructive Migration from Database v12 to v13:
         * Adds bestStreakDays so a personal best survives a broken streak. Existing rows are
         * backfilled from whatever streak they currently hold (and from pendingStreakBeforeReset
         * if a reset is mid-flight), so users don't start at zero having already earned a streak.
         */
        val MIGRATION_12_13 = object : Migration(12, 13) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL("ALTER TABLE `habits` ADD COLUMN `bestStreakDays` INTEGER NOT NULL DEFAULT 0")
                db.execSQL(
                    "UPDATE `habits` SET `bestStreakDays` = MAX(`streakDays`, `pendingStreakBeforeReset`)"
                )
            }
        }

        fun getDatabase(context: Context): AetherDatabase {
            return INSTANCE ?: synchronized(this) {
                val instance = Room.databaseBuilder(
                    context.applicationContext,
                    AetherDatabase::class.java,
                    "aether_os_database"
                )
                .addMigrations(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4, MIGRATION_4_5, MIGRATION_5_6, MIGRATION_6_7, MIGRATION_7_8, MIGRATION_8_9, MIGRATION_9_10, MIGRATION_10_11, MIGRATION_11_12, MIGRATION_12_13)
                .fallbackToDestructiveMigrationOnDowngrade() // Safe fallback on downgrade only
                // NOTE: no blanket fallbackToDestructiveMigration() here on purpose.
                // Every schema version bump must ship an explicit Migration, or real user
                // data would be silently wiped on update instead of failing loudly in testing.
                .addCallback(object : Callback() {
                    override fun onCreate(db: SupportSQLiteDatabase) {
                        super.onCreate(db)
                        // PRODUCTION: first-ever launch must start empty (Clean Slate),
                        // never with invented demo tasks/meals/history.
                        // Demo data is only ever loaded on-demand from Settings via loadDemoData().
                        CoroutineScope(Dispatchers.IO).launch {
                            val dbInstance = getDatabase(context.applicationContext)
                            populateCleanSlate(dbInstance, AppLanguage.SPANISH)
                        }
                    }
                })
                .build()
                INSTANCE = instance
                instance
            }
        }

