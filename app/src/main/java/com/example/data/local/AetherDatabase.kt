        /**
         * Migration from Database v1 to v2:
         * Recreates the `biometrics` table with an autogenerated integer primary key `id`
         * and a unique index on `date` to prevent duplicate daily collisions.
         */
        val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL("DROP TABLE IF EXISTS biometrics_old")
                db.execSQL("ALTER TABLE biometrics RENAME TO biometrics_old")
                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS `biometrics` (
                        `id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
                        `date` TEXT NOT NULL,
                        `readinessScore` INTEGER NOT NULL,
                        `perceivedEnergy` INTEGER NOT NULL,
                        `sleepHours` REAL NOT NULL,
                        `sleepQuality` INTEGER NOT NULL,
                        `chronotype` TEXT NOT NULL,
                        `recoveryModeTriggered` INTEGER NOT NULL,
                        `graceDayActive` INTEGER NOT NULL
                    )
                    """.trimIndent()
                )
                db.execSQL("CREATE UNIQUE INDEX IF NOT EXISTS `index_biometrics_date` ON `biometrics` (`date`)")
                db.execSQL(
                    """
                    INSERT OR REPLACE INTO `biometrics` (
                        `date`, `readinessScore`, `perceivedEnergy`, `sleepHours`, `sleepQuality`, `chronotype`, `recoveryModeTriggered`, `graceDayActive`
                    )
                    SELECT `date`, `readinessScore`, `perceivedEnergy`, `sleepHours`, `sleepQuality`, `chronotype`, `recoveryModeTriggered`, `graceDayActive`
                    FROM `biometrics_old`
                    """.trimIndent()
                )
                db.execSQL("DROP TABLE IF EXISTS biometrics_old")
            }
        }

